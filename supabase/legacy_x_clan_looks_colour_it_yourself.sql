SELECT DISTINCT o.user_id, m.new_id FROM legacy_x.clan_look_owned_player o JOIN clan_moves m ON m.old_id = o.item_id
ON CONFLICT (user_id, item_id) DO NOTHING;

-- The colours a clan wears move with it (a colour it had already picked stays).
INSERT INTO legacy_x.clan_look_custom (clan_id, item_id, color_a, color_b, updated_at)
SELECT e.clan_id, m.new_id, coalesce(c.color_a, m.a), CASE WHEN m.b IS NULL THEN NULL ELSE coalesce(c.color_b, m.b) END, now()
FROM legacy_x.clan_look_equipped e JOIN clan_moves m ON m.old_id = e.item_id
LEFT JOIN legacy_x.clan_look_custom c ON c.clan_id = e.clan_id AND c.item_id = e.item_id
ON CONFLICT (clan_id, item_id) DO UPDATE SET color_a = EXCLUDED.color_a, color_b = EXCLUDED.color_b, updated_at = now();

UPDATE legacy_x.clan_look_equipped e SET item_id = m.new_id, updated_at = now() FROM clan_moves m WHERE e.item_id = m.old_id AND e.item_id <> m.new_id;
COMMIT;
