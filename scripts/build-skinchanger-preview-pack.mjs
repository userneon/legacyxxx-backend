#!/usr/bin/env node
/**
 * Builds a small local-only preview pack from genuine CS2 catalog entries.
 * It writes WebP files and a typed fixture into the isolated production frontend
 * feature worktree. It never writes a database or calls production APIs.
 */
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const sourceBase = "https://raw.githubusercontent.com/ByMykel/CSGO-API/main/public/api/en";
const frontendRoot = path.resolve(new URL("../../legacyxxx-frontend-skinchanger-live", import.meta.url).pathname);
const assetRoot = path.join(frontendRoot, "public", "skinchanger-preview");
const fixturePath = path.join(frontendRoot, "src", "dev", "skinchanger-preview-fixtures.ts");

async function catalog(name) {
  const response = await fetch(`${sourceBase}/${name}`);
  if (!response.ok) throw new Error(`${name} returned ${response.status}`);
  return response.json();
}

function findOrFirst(rows, matcher) {
  return rows.find(matcher) ?? rows.find((row) => row.image) ?? rows[0];
}

function slug(value) {
  return value.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");
}

async function writeWebp(item, fileName) {
  const response = await fetch(item.image);
  if (!response.ok) throw new Error(`image for ${item.name} returned ${response.status}`);
  const buffer = Buffer.from(await response.arrayBuffer());
  const output = await sharp(buffer, { failOn: "none" })
    .rotate()
    .resize({ width: 640, height: 480, fit: "inside", withoutEnlargement: true })
    .webp({ quality: 84, effort: 4 })
    .toBuffer();
  await fs.writeFile(path.join(assetRoot, fileName), output);
}

const [skins, agents, music, collectibles, weapons] = await Promise.all([
  catalog("skins_not_grouped.json"),
  catalog("agents.json"),
  catalog("music_kits.json"),
  catalog("collectibles.json"),
  catalog("base_weapons.json"),
]);

const selections = [
  ["weapon", findOrFirst(skins, (item) => /AK-47 \| Redline/i.test(item.name)), "weapon.webp"],
  ["weapon_skin", findOrFirst(skins, (item) => /M4A1-S \| Printstream/i.test(item.name)), "weapon-skin.webp"],
  ["knife", findOrFirst(skins, (item) => /Karambit \| Doppler/i.test(item.name)), "knife.webp"],
  ["glove", findOrFirst(skins, (item) => /Moto Gloves \| Spearmint/i.test(item.name)), "glove.webp"],
  ["agent", findOrFirst(agents, (item) => /Sir Bloody Silent Darryl/i.test(item.name)), "agent.webp"],
  ["music_kit", findOrFirst(music, (item) => /EZ4ENCE/i.test(item.name)), "music-kit.webp"],
  ["pin", findOrFirst(collectibles.filter((item) => /pin|collectible/i.test(`${item.name} ${item.type ?? ""}`)), () => true), "pin.webp"],
];

await fs.mkdir(assetRoot, { recursive: true });
await fs.mkdir(path.dirname(fixturePath), { recursive: true });
for (const [, item, fileName] of selections) await writeWebp(item, fileName);

const fixtureItems = selections.map(([category, item, fileName], index) => ({
  id: `preview-${category}-${index + 1}`,
  external_key: `preview:${category}:${slug(item.id ?? item.name)}`,
  category,
  weapon_class: item.weapon?.name ?? item.category ?? null,
  display_name: item.name,
  weapon_defindex: item.weapon?.id ?? item.defindex ?? null,
  paint_id: item.paint_index ?? item.paint_id ?? null,
  model: item.model_player ?? item.model ?? null,
  image_key: `skinchanger-preview/${fileName}`,
  image_url: `/skinchanger-preview/${fileName}`,
  metadata: { source: "bymykel-csgo-api", previewOnly: true },
}));

const source = `/** Genuine CS2 preview samples. Generated by scripts/build-skinchanger-preview-pack.mjs. */\nimport type { SkinchangerCatalogItem } from "@/api/skinchanger"\n\nexport const skinchangerPreviewFixtures: SkinchangerCatalogItem[] = ${JSON.stringify(fixtureItems, null, 2)}\n`;
await fs.writeFile(fixturePath, source);
console.log(JSON.stringify({ items: fixtureItems.map((item) => ({ category: item.category, name: item.display_name, image: item.image_url })) }, null, 2));
